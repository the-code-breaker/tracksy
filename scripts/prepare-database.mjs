import { readdir, readFile, writeFile } from "node:fs/promises";
const directory = new URL("../supabase/migrations/", import.meta.url);
const names = (await readdir(directory))
  .filter((name) => /^\d+_[a-z_]+\.sql$/.test(name))
  .sort();
const parts = await Promise.all(
  names.map(
    async (name) =>
      `\n-- ${name}\n${await readFile(new URL(name, directory), "utf8")}`,
  ),
);
await writeFile(
  new URL("../supabase/bootstrap.sql", import.meta.url),
  `-- Tracksy: clean Supabase projects ONLY. Review before running in the SQL editor.\n-- Existing projects must use versioned Supabase CLI migrations instead.\n-- Generated by npm run db:prepare; do not edit this generated file.\nbegin;\n${parts.join("\n")}\ncommit;\n`,
);
console.log(
  `Prepared supabase/bootstrap.sql from ${names.length} migrations. No database was contacted.`,
);
